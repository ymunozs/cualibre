  init() {
    let stored = null;
    try { stored = localStorage.getItem("cua-lang"); } catch (_) { /* sin almacenamiento */ }
    const browser = (navigator.language || "es").slice(0, 2).toLowerCase();
    this.lang = this.LANGS.includes(stored) ? stored
      : this.LANGS.includes(browser) ? browser : "es";
    const select = document.getElementById("lang-select");
    if (select) {
      select.textContent = "";
      for (const code of this.LANGS) {
        const option = document.createElement("option");
        option.value = code;
        option.textContent = this.NAMES[code];
        select.appendChild(option);
      }
      select.value = this.lang;
      select.addEventListener("change", () => this.setLang(select.value));
    }
    this.apply();
  },

  get locale() { return this.LOCALES[this.lang]; },
  get mod() { return this.isMac ? "⌘" : "Ctrl+"; },

  t(key, params = {}) {
    let text = this.dict[this.lang][key] ?? this.dict.es[key] ?? key;
    const values = { mod: this.mod, ...params };
    return text.replace(/\{(\w+)\}/g, (match, name) => (name in values ? values[name] : match));
  },

  domain(key) {
    return (this.DOMAINS[this.lang] || {})[key] || key;
  },
  emotion(key) {
    return (this.EMOTIONS[this.lang] || {})[key] || key;
  },
  _relation(key) {
    return this.RELATIONS[this.lang][key] || this.RELATIONS.es[key] || [key, key, "?"];
  },
  relType(key) { return this._relation(key)[0]; },
  relVerb(key) { return this._relation(key)[1]; },
  relLetter(key) { return this._relation(key)[2]; },

  /* Fecha ISO guardada → texto local breve (los datos no cambian). */
  dateTime(iso) {
    const date = new Date(iso);
    if (isNaN(date)) return String(iso).replace("T", " ");
    // Un formateador por idioma, reutilizado: crear uno por llamada (lo que
    // hace toLocaleString) costaba ~1 ms y se llama miles de veces
    if (!this._dateFormat || this._dateFormat.lang !== this.lang) {
      this._dateFormat = {
        lang: this.lang,
        fmt: new Intl.DateTimeFormat(this.locale, { dateStyle: "short", timeStyle: "short" }),
      };
    }
    return this._dateFormat.fmt.format(date);
  },

  /* Aplica las traducciones al texto estático del HTML. */
  apply(root = document) {
    document.documentElement.lang = this.locale;
    root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = this.t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = this.t(el.dataset.i18nHtml); });
    root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = this.t(el.dataset.i18nTitle); });
    root.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = this.t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", this.t(el.dataset.i18nAria)); });
    // Descargas directas: el servidor no ve la cabecera, así que va en la URL
    root.querySelectorAll("a[data-download]").forEach(a => {
      const url = a.dataset.download;
      a.href = `${url}${url.includes("?") ? "&" : "?"}ui=${this.lang}`;
    });
  },

  onChange(fn) { this._listeners.push(fn); },

  setLang(lang) {
    if (!this.LANGS.includes(lang) || lang === this.lang) return;
    this.lang = lang;
    try { localStorage.setItem("cua-lang", lang); } catch (_) { /* preferencia no persistente */ }
    const select = document.getElementById("lang-select");
    if (select) select.value = lang;
    this.apply();
    for (const fn of this._listeners) {
      try { fn(lang); } catch (error) { console.error(error); }
    }
  },
